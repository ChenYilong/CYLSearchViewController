#!/usr/bin/env python3
"""Copies the iOS resource bundle (Resources/CYLSearchViewController.bundle) into the cylsearch module.

Images: CYLSearchNoResults@2x.png -> res/drawable-xhdpi/cyl_search_no_results.png.
Strings: "search.cancel" in <lang>.lproj/CYLSearchViewController.strings -> <string name="cyl_search_cancel">
in res/values[-<lang>]/cyl_search_strings.xml, with iOS format specifiers turned into Java ones.
Run from any directory: python3 android/merged/scripts/import-ios-resources.py
"""
import os, re, shutil, sys
from xml.sax.saxutils import escape

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
BUNDLE = os.path.join(ROOT, 'Resources', 'CYLSearchViewController.bundle')
RES = os.path.join(ROOT, 'android', 'merged', 'cylsearch', 'src', 'main', 'res')
LANGS = {'en': 'values', 'ja': 'values-ja', 'zh-Hans': 'values-b+zh+Hans', 'zh-Hant': 'values-b+zh+Hant'}

def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()

def android_format(value):
    value = re.sub(r'%(\d+\$)?l?[ud]', lambda m: '%' + (m.group(1) or '') + 'd', value)
    value = re.sub(r'%(\d+\$)?@', lambda m: '%' + (m.group(1) or '') + 's', value)
    value = escape(value).replace("'", "\\'").replace('"', '\\"')
    return value

def main():
    drawable = os.path.join(RES, 'drawable-xhdpi')
    os.makedirs(drawable, exist_ok=True)
    for name in sorted(os.listdir(BUNDLE)):
        match = re.fullmatch(r'(CYLSearch\w+?)(@2x)?\.png', name)
        if match:
            target = 'cyl_search_' + snake(match.group(1)[len('CYLSearch'):]) + '.png'
            shutil.copyfile(os.path.join(BUNDLE, name), os.path.join(drawable, target))
    for lang, folder in LANGS.items():
        path = os.path.join(BUNDLE, lang + '.lproj', 'CYLSearchViewController.strings')
        text = open(path, encoding='utf-8').read()
        pairs = re.findall(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', text, re.M)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 '<!-- Generated by scripts/import-ios-resources.py from the iOS ' + lang + '.lproj. Do not edit. -->',
                 '<resources>']
        for key, value in pairs:
            value = value.replace('\\"', '"').replace('\\n', '\n')
            formatted = '' if re.search(r'%(\d+\$)?l?[ud@]', value) else ' formatted="false"' if '%' in value else ''
            lines.append(f'    <string name="cyl_{key.replace(".", "_")}"{formatted}>{android_format(value)}</string>')
        lines.append('</resources>')
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        open(os.path.join(RES, folder, 'cyl_search_strings.xml'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('images:', len(os.listdir(drawable)), 'languages:', len(LANGS))

if __name__ == '__main__':
    sys.exit(main())
