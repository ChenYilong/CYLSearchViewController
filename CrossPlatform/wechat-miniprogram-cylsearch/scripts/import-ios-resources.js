// Imports the resources of the iOS library and example, so the mini program shows the same texts, data and images:
// 1. (none: the placeholder images are CYLTableViewPlaceHolder's, from cyl-placeholder-miniprogram; the search core has no
//    placeholder view of its own any more);
// 2. the texts of CYLSearchViewController.bundle, CYLSearchTabs.bundle and CYLSearchDiscover.bundle (en, ja,
//    zh-Hans, zh-Hant) and the discover data (search-discover.json) into
//    example/miniprogram/utils/cyl_demo_resources.js;
// 3. the localized hot icons (discover-hot@3x.png) into example/miniprogram/assets/discover/.
// The outputs are committed; run again after the iOS resources change: node scripts/import-ios-resources.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const repository = path.join(root, '..', '..');
const libraryBundle = path.join(repository, 'Resources', 'CYLSearchViewController.bundle');
const exampleDir = path.join(repository, 'CYLSearchExample');
const languages = ['en', 'ja', 'zh-Hans', 'zh-Hant'];

/** Reads an Apple .strings file ("key" = "value";) into an object. */
function readStrings(file) {
  const text = fs.readFileSync(file, 'utf8');
  const strings = {};
  const pattern = /^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;/gm;
  let match;
  while ((match = pattern.exec(text))) {
    strings[JSON.parse(`"${match[1]}"`)] = JSON.parse(`"${match[2]}"`);
  }
  return strings;
}

// 2. Texts and discover data, one table per language.
const strings = {};
const discover = {};
for (const language of languages) {
  strings[language] = Object.assign(
    readStrings(path.join(libraryBundle, `${language}.lproj`, 'CYLSearchViewController.strings')),
    readStrings(path.join(exampleDir, 'CYLSearchTabs.bundle', `${language}.lproj`, 'CYLSearchTabs.strings')),
    readStrings(path.join(exampleDir, 'CYLSearchDiscover.bundle', `${language}.lproj`, 'CYLSearchDiscover.strings')),
  );
  const data = JSON.parse(fs.readFileSync(path.join(exampleDir, 'CYLSearchDiscover.bundle', `${language}.lproj`, 'search-discover.json'), 'utf8'));
  delete data.comment;
  discover[language] = data;
}
const output = path.join(root, 'example', 'miniprogram', 'utils', 'cyl_demo_resources.js');
fs.writeFileSync(output, `// Generated by scripts/import-ios-resources.js from the iOS bundles (CYLSearchViewController.bundle,
// CYLSearchTabs.bundle, CYLSearchDiscover.bundle). Do not edit.
module.exports = ${JSON.stringify({ languages, strings, discover }, null, 1)};
`);

// 3. Hot icons, one per language.
const hotDir = path.join(root, 'example', 'miniprogram', 'assets', 'discover');
fs.mkdirSync(hotDir, { recursive: true });
for (const language of languages) {
  fs.copyFileSync(path.join(exampleDir, 'CYLSearchDiscover.bundle', `${language}.lproj`, 'discover-hot@3x.png'),
    path.join(hotDir, `discover-hot-${language}.png`));
}
console.log('imported', languages.length, 'languages');
